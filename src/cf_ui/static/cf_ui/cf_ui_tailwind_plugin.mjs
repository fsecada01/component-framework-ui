/**
 * cf-ui theme composition axes — Tailwind plugin.
 *
 * Validates axis values at build time and generates the axis CSS from the
 * definition exported by `cf_ui/axes.py`. The point is the throw: an unknown
 * axis value stops the build. Without it, `data-accent="hotpink"` is not an
 * error, it is an element with no accent — discovered in review, or in
 * production, instead of at build time.
 *
 * VENDORED FILE. This ships inside the Python package and is loaded from
 * site-packages, so it deliberately imports nothing but Node builtins — a bare
 * `tailwindcss/plugin` import would not resolve from where this file lives.
 * The exported shape is Tailwind's own `{ handler, config }` plugin object,
 * which is exactly what `tailwindcss/plugin` constructs.
 *
 * GENERATED INPUT, HAND-WRITTEN CODE: `cf_ui_axes.json` is a build product of
 * `axes.py` (`python -m cf_ui.axes`). This file must never carry its own copy
 * of the value sets — that is the drift #7 exists to prevent.
 *
 * Usage (Tailwind v4, CSS-first):
 *
 *   @import "tailwindcss";
 *   @plugin "./path/to/site-packages/cf_ui/static/cf_ui/cf_ui_tailwind_plugin.mjs";
 *
 * Usage (JS config, with options):
 *
 *   import cfUiAxes from "./.../cf_ui_tailwind_plugin.mjs";
 *   export default {
 *     plugins: [cfUiAxes({ composition: "console", contrastReport: true })],
 *   };
 */

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const DEFINITION_URL = new URL("./cf_ui_axes.json", import.meta.url);

/** Raised for an unknown axis, value, composition, or malformed value set. */
export class AxisPluginError extends Error {
  constructor(message) {
    super(`cf-ui: ${message}`);
    this.name = "AxisPluginError";
  }
}

let _definitionText = null;

/**
 * Read the axis definition generated by `python -m cf_ui.axes`.
 *
 * Returns a fresh deep copy each call, so a caller merging its own value sets
 * can never corrupt the shipped ones for the next build in the same process.
 */
export function loadDefinition() {
  if (_definitionText === null) {
    _definitionText = readFileSync(fileURLToPath(DEFINITION_URL), "utf-8");
  }
  return JSON.parse(_definitionText);
}

// --- validation ------------------------------------------------------------

/**
 * Token values are interpolated straight into generated CSS. A value carrying
 * `;` or a brace closes its own declaration and writes rules the app never
 * asked for, so it is rejected rather than escaped — there is no legitimate
 * axis token that needs one.
 */
const UNSAFE_VALUE = /[;{}]|\/\*|\*\//;

function validateTokens(axis, name, tokens) {
  if (tokens === null || typeof tokens !== "object" || Array.isArray(tokens)) {
    throw new AxisPluginError(`axis value ${axis}/${name} must be a mapping of custom properties`);
  }
  for (const [token, value] of Object.entries(tokens)) {
    if (!token.startsWith("--")) {
      throw new AxisPluginError(
        `axis value ${axis}/${name} declares '${token}': axis tokens must be CSS custom ` +
          `properties (a name starting with '--')`,
      );
    }
    if (typeof value !== "string") {
      throw new AxisPluginError(`axis value ${axis}/${name} declares a non-string ${token}`);
    }
    if (UNSAFE_VALUE.test(value)) {
      throw new AxisPluginError(
        `axis value ${axis}/${name} declares ${token} with an unsafe value: a token may not ` +
          `contain ';', '{', '}', or a comment delimiter`,
      );
    }
  }
}

function validateValueSet(definition, axis, name, tokens) {
  if (!new RegExp(definition.valueNamePattern).test(name)) {
    throw new AxisPluginError(
      `invalid axis value name '${name}' for axis '${axis}': expected lowercase words ` +
        `separated by hyphens`,
    );
  }
  if (tokens === null || typeof tokens !== "object" || Array.isArray(tokens)) {
    throw new AxisPluginError(`axis value ${axis}/${name} must be a mapping of custom properties`);
  }

  if (definition.modeKeyedAxes.includes(axis)) {
    const missing = definition.modes.filter((mode) => !(mode in tokens));
    if (missing.length) {
      throw new AxisPluginError(
        `axis value ${axis}/${name} is missing ${missing.join(", ")} — light and dark must ` +
          `each be declared explicitly, never derived by inversion`,
      );
    }
    for (const mode of definition.modes) {
      validateTokens(axis, name, tokens[mode]);
    }
    if (tokens.p3) {
      for (const mode of definition.modes) {
        if (tokens.p3[mode]) validateTokens(axis, name, tokens.p3[mode]);
      }
    }
  } else {
    validateTokens(axis, name, tokens);
  }
}

/**
 * Combine an app's own value sets with the shipped ones.
 *
 * Mirrors `cf_ui.axes.merge_value_sets`: `"extend"` adds to (or overrides
 * individual values in) the shipped set; `"replace"` discards the shipped
 * values for each axis supplied, leaving untouched axes at their defaults.
 */
export function mergeValueSets(definition, custom, mode = "extend") {
  if (mode !== "extend" && mode !== "replace") {
    throw new AxisPluginError(`unknown value-set mode '${mode}': expected 'extend' or 'replace'`);
  }

  const merged = structuredClone(definition.valueSets);
  if (!custom) return merged;

  for (const [axis, values] of Object.entries(custom)) {
    if (!definition.axes.includes(axis)) {
      throw new AxisPluginError(
        `unknown axis '${axis}': valid axes are ${definition.axes.join(", ")}`,
      );
    }
    if (values === null || typeof values !== "object") {
      throw new AxisPluginError(`axis '${axis}' must map value names to tokens`);
    }
    for (const [name, tokens] of Object.entries(values)) {
      validateValueSet(definition, axis, name, tokens);
    }
    merged[axis] =
      mode === "replace"
        ? structuredClone(values)
        : { ...merged[axis], ...structuredClone(values) };
  }

  return merged;
}

/**
 * Resolve one config value into a value for each axis, failing the build on
 * anything the value sets do not declare. This is the feature.
 */
export function resolveComposition(definition, composition, valueSets) {
  const base = definition.compositions.default;
  let chosen;

  if (composition === null || composition === undefined) {
    chosen = { ...base };
  } else if (typeof composition === "string") {
    if (!(composition in definition.compositions)) {
      const known = Object.keys(definition.compositions).sort().join(", ");
      throw new AxisPluginError(
        `unknown composition '${composition}': known compositions ${known}`,
      );
    }
    chosen = { ...definition.compositions[composition] };
  } else if (typeof composition === "object" && !Array.isArray(composition)) {
    const unknown = Object.keys(composition).filter((axis) => !definition.axes.includes(axis));
    if (unknown.length) {
      throw new AxisPluginError(
        `unknown axis ${unknown.map((a) => `'${a}'`).join(", ")}: valid axes are ` +
          `${definition.axes.join(", ")}`,
      );
    }
    chosen = { ...base, ...composition };
  } else {
    throw new AxisPluginError(
      `composition must be a name, a mapping of axes, or null — got ${typeof composition}`,
    );
  }

  for (const axis of definition.axes) {
    const value = chosen[axis];
    const available = valueSets[axis] ?? {};
    if (!(value in available)) {
      const valid = Object.keys(available).sort().join(", ") || "(none)";
      throw new AxisPluginError(
        `unknown value '${value}' for axis '${axis}': valid values are ${valid}`,
      );
    }
  }

  return chosen;
}

// --- CSS generation --------------------------------------------------------

function selectorFor(definition, axis, value, mode) {
  const attr = `[${definition.axisAttrs[axis]}="${value}"]`;
  return mode === "dark" ? `[data-theme="dark"]${attr}` : attr;
}

/**
 * One rule body: the declared tokens, then the Tailwind theme aliases for
 * whichever of them are present. Mirrors `cf_ui.axes._block` exactly — the
 * parity test in `tests/unit/test_tailwind_plugin.py` compares the output of
 * the two generators declaration by declaration.
 */
function blockFor(definition, tokens) {
  const block = { ...tokens };
  for (const [name, alias] of Object.entries(definition.aliases)) {
    if (name in tokens) block[alias] = `var(${name})`;
  }
  return block;
}

/**
 * Build the axis rules as a Tailwind `addBase` object, wide-gamut layer
 * included.
 */
export function buildAxisBase(valueSets, definition) {
  const def = definition ?? loadDefinition();
  const sets = valueSets ?? def.valueSets;
  const base = {};

  for (const axis of def.axes) {
    for (const [value, tokens] of Object.entries(sets[axis] ?? {})) {
      if (def.modeKeyedAxes.includes(axis)) {
        for (const mode of def.modes) {
          base[selectorFor(def, axis, value, mode)] = blockFor(def, tokens[mode]);
        }
      } else {
        base[selectorFor(def, axis, value)] = blockFor(def, tokens);
      }
    }
  }

  // Generated from the same definition rather than hand-maintained alongside
  // it — keeping the two in sync by hand is what #7 removes.
  const p3 = {};
  for (const axis of def.axes) {
    for (const [value, tokens] of Object.entries(sets[axis] ?? {})) {
      const gamut = tokens && typeof tokens === "object" ? tokens.p3 : null;
      if (!gamut) continue;
      for (const mode of def.modes) {
        if (gamut[mode]) {
          p3[selectorFor(def, axis, value, mode)] = blockFor(def, gamut[mode]);
        }
      }
    }
  }
  if (Object.keys(p3).length) {
    base["@media (color-gamut: p3)"] = p3;
  }

  return base;
}

/** The same rules as CSS text, for writing to a file or eyeballing a build. */
export function buildAxisCss(valueSets, definition) {
  const base = buildAxisBase(valueSets, definition);
  const render = (rules, indent) =>
    Object.entries(rules)
      .map(([selector, block]) => {
        const body = Object.entries(block)
          .map(([name, value]) => `${indent}  ${name}: ${value};`)
          .join("\n");
        return `${indent}${selector} {\n${body}\n${indent}}\n`;
      })
      .join("\n");

  const { "@media (color-gamut: p3)": media, ...flat } = base;
  let css = render(flat, "");
  if (media) css += `\n@media (color-gamut: p3) {\n${render(media, "  ")}}\n`;
  return css;
}

// --- contrast --------------------------------------------------------------

function relativeLuminance(color) {
  let value = String(color).trim().replace(/^#/, "");
  if (value.length === 3) value = [...value].map((char) => char + char).join("");
  if (!/^[0-9a-fA-F]{6}$/.test(value)) return null;

  const channels = [0, 2, 4].map((index) => {
    const channel = parseInt(value.slice(index, index + 2), 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
}

/** WCAG 2.1 relative-luminance contrast ratio between two sRGB hex colors. */
export function contrastRatio(foreground, background) {
  const first = relativeLuminance(foreground);
  const second = relativeLuminance(background);
  if (first === null || second === null) return null;
  return (Math.max(first, second) + 0.05) / (Math.min(first, second) + 0.05);
}

/**
 * Every accent x surface x mode combination, with its WCAG AA failures.
 *
 * Advisory by design: this warns, it does not fail the build. The build error
 * is reserved for an unknown axis value, which is unambiguously a mistake. A
 * contrast number below AA may be a deliberate choice in a value set the
 * package did not ship, and turning it into a hard error would mean cf-ui
 * decides when a consuming app is allowed to compile.
 */
export function contrastReport(valueSets, contrastPairs, modes = ["light", "dark"]) {
  const rows = [];
  for (const accent of Object.keys(valueSets.accent ?? {})) {
    for (const surface of Object.keys(valueSets.surface ?? {})) {
      for (const mode of modes) {
        const tokens = {
          ...(valueSets.surface[surface][mode] ?? {}),
          ...(valueSets.accent[accent][mode] ?? {}),
        };
        const failures = [];
        for (const { foreground, background, minimum } of contrastPairs) {
          if (!(foreground in tokens) || !(background in tokens)) {
            failures.push(`${foreground} on ${background}: token not declared`);
            continue;
          }
          const ratio = contrastRatio(tokens[foreground], tokens[background]);
          if (ratio === null) {
            failures.push(
              `${foreground} on ${background}: not an sRGB hex value, cannot be checked`,
            );
          } else if (ratio < minimum) {
            failures.push(`${foreground} on ${background}: ${ratio.toFixed(2)} < ${minimum}`);
          }
        }
        rows.push({ accent, surface, mode, failures });
      }
    }
  }
  return rows;
}

function warnContrast(rows) {
  const failing = rows.filter((row) => row.failures.length);
  if (!failing.length) {
    console.warn(`cf-ui: contrast report — ${rows.length} combinations checked, all pass WCAG AA`);
    return;
  }
  const lines = failing.map(
    (row) => `  ${row.accent} x ${row.surface} (${row.mode}):\n    ${row.failures.join("\n    ")}`,
  );
  console.warn(
    `cf-ui: contrast report — ${failing.length} of ${rows.length} combinations fail ` +
      `WCAG AA:\n${lines.join("\n")}`,
  );
}

// --- plugin ----------------------------------------------------------------

/**
 * @param {object}  [options]
 * @param {object}  [options.definition]     Override the shipped definition.
 * @param {object}  [options.valueSets]      The app's own `{axis: {name: tokens}}`.
 * @param {string}  [options.valueSetsMode]  `"extend"` (default) or `"replace"`.
 * @param {string|object|null} [options.composition] Validated, and it is the
 *   validation that matters — an unknown value throws here.
 * @param {boolean} [options.contrastReport] Warn with the full accent x
 *   surface x mode report. Off by default.
 */
function createPlugin(options = {}) {
  const definition = options.definition ?? loadDefinition();
  const valueSets = mergeValueSets(
    definition,
    options.valueSets,
    options.valueSetsMode ?? "extend",
  );

  // Eager, so the build fails at the point of misconfiguration rather than
  // whenever Tailwind happens to invoke the handler.
  resolveComposition(definition, options.composition ?? null, valueSets);

  if (options.contrastReport) {
    warnContrast(contrastReport(valueSets, definition.contrastPairs, definition.modes));
  }

  const base = buildAxisBase(valueSets, definition);
  return {
    handler: ({ addBase }) => addBase(base),
    config: {},
  };
}

/**
 * Callable as a factory (`cfUiAxes({...})`) and usable directly as a plugin
 * (`@plugin "./cf_ui_tailwind_plugin.mjs"`), which is the shape Tailwind's own
 * `plugin.withOptions` produces.
 */
const cfUiAxes = (options = {}) => createPlugin(options);
Object.assign(cfUiAxes, createPlugin({}));

export default cfUiAxes;
